#!/usr/bin/env python3
"""Generate the diagnostic config set from the committed configs.

Runs on VM-Mon. The repository configs are never modified: every variant is a
copy written to bench/diag_cfg/, together with a compose file that points the
arm at it. That keeps the official sweep path physically untouched - there is no
window in which a half-applied diagnostic config could be measured as thesis data.

Parity applied to every variant (both arms, always)
  Vector  host_key: ""            -> one per-event attribute, like OTel's log.file.name
  OTel    collectors: [six]       -> same six host metrics Vector collects (was eight)

Variants
  vector-base / otel-base         the study's pipeline, plus parity
  vector-readonly / otel-readonly source -> discard, no transform at all
  vector-parseonly / otel-parseonly  source -> JSON parse -> discard
  otel-poll50                     base with poll_interval 200ms -> 50ms
"""
import os
import re
import sys

BENCH = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BENCH, "diag_cfg")

HOST_COLLECTORS = "[cpu, memory, disk, network, filesystem, load]"

COMPOSE = """# generated by experiments/make_configs.py - do not edit, do not commit
services:
  {service}:
    image: {image}
    container_name: {cname}
    network_mode: host
    cpuset: "${{AGENT_CPUSET:-2-3}}"
    mem_limit: 1536m
    user: "0:0"
    restart: "no"
    command: [{cmd}]
    environment:
      PROCFS_ROOT: /hostfs/proc
      SYSFS_ROOT: /hostfs/sys
    volumes:
      - {cfg}:/etc/{dest}:ro
      - {BENCH}/logs:/logs:ro
      - /:/hostfs:ro
"""


def read(name):
    return open(os.path.join(BENCH, "configs", name)).read()


def vector_base():
    src = read("vector.yaml")
    # one read slice, one attribute: the study config plus parity
    if "max_read_bytes:" not in src:
        src = src.replace("    ignore_checkpoints: true\n",
                          "    ignore_checkpoints: true\n    max_read_bytes: 16384\n", 1)
    src = re.sub(r"\n[ \t]*host_key:.*", "", src)
    src = re.sub(r"\n([ \t]*)file_key:.*", "", src)
    src = src.replace("    max_read_bytes:", '    host_key: ""\n    max_read_bytes:', 1)
    return src


def vector_variant(stage):
    src = vector_base()
    head = src[:src.index("transforms:")]
    tail = src[src.index("sinks:"):]
    if stage == "readonly":
        return head + tail.replace("inputs: [enrich]", "inputs: [logs]")
    if stage == "parseonly":
        return (head
                + "transforms:\n  enrich:\n    type: remap\n    inputs: [logs]\n"
                  "    source: |\n      . = parse_json!(.message)\n"
                + tail)
    return src


def otel_base():
    src = read("otel.yaml")
    if "collectors:" not in src.split("host_metrics:", 1)[-1].split("service:", 1)[0]:
        src = src.replace("    root_path: /hostfs\n",
                          "    root_path: /hostfs\n    collectors: " + HOST_COLLECTORS + "\n", 1)
    return src


def otel_variant(stage):
    src = otel_base()
    if stage == "readonly":
        return src.replace(
            "logs: {receivers: [file_log], processors: [transform/enrich], exporters: [nop]}",
            "logs: {receivers: [file_log], processors: [], exporters: [nop]}")
    if stage == "parseonly":
        start = src.index("    log_statements:")
        end = src.index("exporters:")
        block = ("    log_statements:\n      - context: log\n        statements:\n"
                 "          - merge_maps(attributes, ParseJSON(body), \"upsert\")\n")
        return src[:start] + block + src[end:]
    if stage == "poll50":
        return src.replace("    start_at: beginning\n",
                           "    start_at: beginning\n    poll_interval: 50ms\n", 1)
    return src


def write(name, text):
    path = os.path.join(OUT, name)
    open(path, "w").write(text)
    return path


def compose(name, service, image, cname, cfg, dest, cmd):
    return write(name, COMPOSE.format(service=service, image=image, cname=cname,
                                      cfg=cfg, dest=dest, cmd=cmd, BENCH=BENCH))


def main():
    os.makedirs(OUT, exist_ok=True)
    made = []

    for stage in ("base", "readonly", "parseonly"):
        cfg = write(f"vector-{stage}.yaml", vector_variant(stage))
        made.append(compose(f"compose.vector.{stage}.yml", "vector",
                            "timberio/vector:0.59.0-debian", "v-vector",
                            cfg, "vector/vector.yaml", '"--config", "/etc/vector/vector.yaml"'))
        made.append(cfg)

    for stage in ("base", "readonly", "parseonly", "poll50"):
        cfg = write(f"otel-{stage}.yaml", otel_variant(stage))
        made.append(compose(f"compose.otel.{stage}.yml", "otel",
                            "otel/opentelemetry-collector-contrib:0.162.0", "o-otel",
                            cfg, "otelcol-contrib/config.yaml",
                            '"--config=/etc/otelcol-contrib/config.yaml"'))
        made.append(cfg)

    print(f"wrote {len(made)} files to {OUT}")
    for m in sorted(made):
        print("  " + os.path.basename(m))


if __name__ == "__main__":
    sys.exit(main())
